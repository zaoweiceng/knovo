const store = new Store(root, path.join(root, ".knowledge"));
let count = 0;
try {
  for (const e of entries) {
    if (store.db.prepare("SELECT 1 FROM notes WHERE id=?").get(e.id)) continue;
    const note = {
      schema_version: 1,
      status: "ready",
      tags: [],
      knowledge_keywords: [e.title],
      dependency_keywords: [],
      aliases: [],
      merged_from: [],
      created_at: now,
      updated_at: now,
      learning_events: [{ date: day(), summary: "阅读并体验示例知识点。" }],
      ...e,
    };
    store.import(serializeNote(note), e.id + ".md", { createOnly: true });
    count++;
  }
} finally {
  store.close();
}
console.log(
  `已写入 ${count} 篇明确标记的示例笔记；全部以 demo- 开头，可随时删除。`,
);
